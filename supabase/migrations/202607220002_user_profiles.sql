-- Unique migration version; this SQL was originally applied manually on 2026-07-22.
-- Public creator profiles, case-insensitive username uniqueness, and a
-- database-enforced rolling limit of three username changes per year.

create table if not exists public.user_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  avatar_url text,
  avatar_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_profiles_username_format check (
    username = btrim(username)
    and char_length(username) between 3 and 30
    and username ~ '^[A-Za-z0-9_][A-Za-z0-9 _.-]{2,29}$'
  )
);

create unique index if not exists user_profiles_username_lower_uidx
  on public.user_profiles (lower(username));

create table if not exists public.user_username_changes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  old_username text not null,
  new_username text not null,
  changed_at timestamptz not null default now()
);

create index if not exists user_username_changes_user_time_idx
  on public.user_username_changes (user_id, changed_at desc);

alter table public.user_profiles enable row level security;
alter table public.user_username_changes enable row level security;

drop policy if exists "Public profiles are readable" on public.user_profiles;
create policy "Public profiles are readable"
  on public.user_profiles for select
  using (true);

drop policy if exists "Users can read their username history" on public.user_username_changes;
create policy "Users can read their username history"
  on public.user_username_changes for select
  using (auth.uid() = user_id);

